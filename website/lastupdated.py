"""MkDocs hook: "Last updated <date>" at the foot of every page (Ken, 2026-11-16), the date of the last git commit
that changed the page's source in this repository.

The site's pages are copies staged under their repository paths, so a page's source is usually the file of the same
path. The exceptions: index.md is website/home.md, repository.md is the repository README, a notes.md stands for the
README.md beside it, and pages generated by stage.py name their source in mkdocs.yml (extra: last_updated_sources:
a page path, or a folder of pages ending in /, mapped to the file or folder they are made from; {name} in the source
is the page's file name without .md). A page with no source found gets no line.

The same file in YACC1-D, p8x, elf and P32W. The GitHub workflow checks out the whole history (fetch-depth: 0), or
every page would carry the date of the last commit."""
import datetime, os, posixpath, subprocess

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))   # the repository this folder is in
_dates = {}


def commit_date(path):
    """The date of the last commit that changed path (a file or a folder), or None. The history is read once (one
    git log over every commit, newest first): asking git once per page made the build twenty times slower."""
    if not _dates:
        r = subprocess.run(["git", "-C", REPO, "log", "--format=@%cs", "--name-only"], capture_output=True, text=True)
        date = None
        for line in r.stdout.splitlines():
            if line.startswith("@"): date = line[1:]
            elif line and line not in _dates: _dates[line] = date
        _dates.setdefault("", None)
    if path in _dates: return _dates[path]
    under = [d for p, d in _dates.items() if d and p.startswith(path.rstrip("/") + "/")]
    return max(under) if under else None


def source_of(uri, extra):
    if uri == "index.md": return "website/home.md"
    if uri == "repository.md": return "README.md"
    if posixpath.basename(uri) == "notes.md":
        readme = posixpath.join(posixpath.dirname(uri), "README.md")
        if os.path.exists(os.path.join(REPO, readme)): return readme
    if os.path.exists(os.path.join(REPO, uri)): return uri
    sources = (extra or {}).get("last_updated_sources") or {}
    name = posixpath.splitext(posixpath.basename(uri))[0]
    if uri in sources: return sources[uri].format(name=name)
    for prefix, src in sources.items():
        if prefix.endswith("/") and uri.startswith(prefix): return src.format(name=name)
    return None


def on_page_markdown(markdown, page, config, files):
    src = source_of(page.file.src_uri, config.get("extra"))
    date = commit_date(src) if src else None
    if not date: return markdown
    shown = datetime.date.fromisoformat(date).strftime("%-d %B %Y")
    return markdown.rstrip() + '\n\n<p class="last-updated"><small>Last updated %s</small></p>\n' % shown
